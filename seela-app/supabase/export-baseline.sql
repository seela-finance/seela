CREATE OR REPLACE FUNCTION pg_temp.run_sql(q text) RETURNS text LANGUAGE plpgsql AS $f$
DECLARE r text;
BEGIN
  EXECUTE q INTO r;
  RETURN r;
EXCEPTION WHEN others THEN
  RETURN 'ERREUR ' || SQLSTATE || ' ' || SQLERRM;
END $f$;

SELECT pg_temp.run_sql($q$
WITH
tbls AS (
  SELECT c.oid, c.relname, c.relrowsecurity
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
),
stmts AS (
  SELECT 0 AS ord, e.extname::text AS k,
    format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname) AS sql
  FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
  WHERE e.extname <> 'plpgsql'

  UNION ALL
  SELECT 1, t.typname::text,
    format('CREATE TYPE public.%I AS ENUM (%s);', t.typname,
      (SELECT string_agg(quote_literal(enumlabel), ', ' ORDER BY enumsortorder) FROM pg_enum WHERE enumtypid = t.oid))
  FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
  WHERE n.nspname = 'public' AND t.typtype = 'e'

  UNION ALL
  SELECT 2, c.relname::text, format('CREATE SEQUENCE IF NOT EXISTS public.%I;', c.relname)
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind = 'S'
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'i')

  UNION ALL
  SELECT 3, p.proname::text || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    pg_get_functiondef(p.oid) || ';'
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind IN ('f', 'p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')

  UNION ALL
  SELECT 4, t.relname::text,
    format(E'CREATE TABLE public.%I (\n%s\n);', t.relname,
      (SELECT string_agg(
          format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
          || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                                WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
          || CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                  WHEN ad.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid) ELSE '' END
          || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
          E',\n' ORDER BY a.attnum)
       FROM pg_attribute a
       LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
       WHERE a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped))
  FROM tbls t

  UNION ALL
  SELECT CASE WHEN co.contype = 'f' THEN 6 ELSE 5 END, t.relname::text || '.' || co.conname,
    format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  FROM pg_constraint co JOIN tbls t ON t.oid = co.conrelid
  WHERE co.contype IN ('p', 'u', 'c', 'f', 'x')

  UNION ALL
  SELECT 7, ic.relname::text, pg_get_indexdef(i.indexrelid) || ';'
  FROM pg_index i JOIN tbls t ON t.oid = i.indrelid JOIN pg_class ic ON ic.oid = i.indexrelid
  WHERE NOT EXISTS (SELECT 1 FROM pg_constraint co WHERE co.conindid = i.indexrelid)

  UNION ALL
  SELECT 8, c.relname::text, format('CREATE VIEW public.%I AS %s', c.relname, pg_get_viewdef(c.oid))
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind = 'v'

  UNION ALL
  SELECT 9, n.nspname || '.' || c.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  FROM pg_trigger tg JOIN pg_class c ON c.oid = tg.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE NOT tg.tgisinternal AND (n.nspname = 'public' OR (n.nspname = 'auth' AND c.relname = 'users'))

  UNION ALL
  SELECT 10, t.relname::text, format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t.relname)
  FROM tbls t WHERE t.relrowsecurity

  UNION ALL
  SELECT 11, p.schemaname || '.' || p.tablename || '.' || p.policyname,
    format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
      p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
      (SELECT string_agg(quote_ident(r), ', ') FROM unnest(p.roles) r),
      coalesce(' USING (' || p.qual || ')', ''),
      coalesce(' WITH CHECK (' || p.with_check || ')', ''))
  FROM pg_policies p
  WHERE p.schemaname = 'public' OR (p.schemaname = 'storage' AND p.tablename = 'objects')

  UNION ALL
  SELECT 12, b.id,
    format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %L, %L, %L) ON CONFLICT (id) DO NOTHING;',
      b.id, b.name, b.public, b.file_size_limit, b.allowed_mime_types)
  FROM storage.buckets b
)
SELECT E'SET check_function_bodies = false;\n\n' || (SELECT string_agg(sql, E'\n\n' ORDER BY ord, k) FROM stmts) AS baseline
$q$) AS baseline;
